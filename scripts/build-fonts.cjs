/**
 * Builds `site/fonts.css` from the woff2 files in `site/fonts/`.
 *
 * Why the fonts are inlined rather than linked.
 *
 * Chromium refuses to load a font from `file://` as a cross-origin request:
 *
 *   Access to font at 'file:///.../inter-cyrillic.woff2' from origin 'null' has
 *   been blocked by CORS policy: Cross origin requests are only supported for
 *   protocol schemes: ... data, edge, http, https
 *
 * So `url('fonts/inter-cyrillic.woff2')` works when the page is served over
 * HTTP and silently fails when the same page is opened by double-clicking it —
 * which is exactly how this site is meant to be previewed and handed over. The
 * failure is invisible on a machine that happens to have Inter installed, and
 * obvious nowhere else: the text simply renders in the fallback face.
 *
 * A `data:` URL is on the allowed list, so inlining makes the file:// case work
 * and costs nothing over HTTP beyond the base64 overhead (~4/3 of 105 KB).
 *
 * Usage: node scripts/build-fonts.cjs
 */

const path = require('node:path')
const fs = require('node:fs/promises')

const SITE = path.join(__dirname, '..', 'site')
const FONTS = path.join(SITE, 'fonts')

/**
 * The four faces the page needs. Cyrillic and Latin are separate files because
 * Google Fonts ships them as subsets; each is declared with its own
 * `unicode-range` so a browser only rasterises the glyphs it is asked for.
 */
const FACES = [
  {
    family: 'Inter',
    weight: '400 700',
    file: 'inter-cyrillic.woff2',
    range:
      'U+0301, U+0400-045F, U+0490-0491, U+04B0-04B1, U+2116'
  },
  {
    family: 'Inter',
    weight: '400 700',
    file: 'inter-latin.woff2',
    range:
      'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD'
  },
  {
    family: 'JetBrains Mono',
    weight: '400 600',
    file: 'jetbrains-mono-cyrillic.woff2',
    range: 'U+0301, U+0400-045F, U+0490-0491, U+04B0-04B1, U+2116'
  },
  {
    family: 'JetBrains Mono',
    weight: '400 600',
    file: 'jetbrains-mono-latin.woff2',
    range:
      'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD'
  }
]

async function main() {
  const header = `/* Generated by scripts/build-fonts.cjs — do not edit by hand.
 *
 * Inter and JetBrains Mono, SIL Open Font License 1.1 (see fonts/ЛИЦЕНЗИИ.txt).
 * Inlined as data: URLs because a font loaded from file:// is blocked by CORS,
 * so the page would fall back to a system face when opened by double-click.
 * Only the Cyrillic and Latin subsets are included.
 */
`

  let css = header
  let binary = 0

  for (const face of FACES) {
    const file = path.join(FONTS, face.file)
    const bytes = await fs.readFile(file)
    binary += bytes.length
    const base64 = bytes.toString('base64')

    css += `
@font-face {
  font-family: '${face.family}';
  font-style: normal;
  font-weight: ${face.weight};
  font-display: swap;
  src: url('data:font/woff2;base64,${base64}') format('woff2');
  unicode-range: ${face.range};
}
`
    console.log(`${face.family} ${face.file.padEnd(28)} ${(bytes.length / 1024).toFixed(1)} KB`)
  }

  const out = path.join(SITE, 'fonts.css')
  await fs.writeFile(out, css, 'utf8')
  const stat = await fs.stat(out)
  console.log(`\nfonts.css  ${(stat.size / 1024).toFixed(0)} KB  (${(binary / 1024).toFixed(0)} KB of woff2, ${FACES.length} faces)`)
}

main().catch((error) => {
  console.error('FAILED', error)
  process.exit(1)
})
